using System.Net;
using System.Net.Http.Headers;
using System.Net.Http.Json;
using System.Text;
using System.Text.Json;
using RouteFinder.Core;

namespace RouteFinder.Service;

/// <summary>Experimental interop adapter reconstructed from decoded constant records, not runtime-verified service code.</summary>
public sealed class EzConnectClient : IDisposable
{
    readonly HttpClient http;
    static readonly Uri LoginOrigin = new("https://desktop-windows-app-login.ezconnect.ir");
    static readonly Uri PoolOrigin = new("https://desktop-windows-app.ezconnect.ir");
    const int MaxResponseBytes = 8 * 1024 * 1024;
    public EzConnectClient(HttpMessageHandler? handler = null, TimeSpan? requestTimeout = null)
    {
        http = new HttpClient(handler ?? new HttpClientHandler { AllowAutoRedirect = false }, true) { Timeout = requestTimeout ?? TimeSpan.FromSeconds(30) };
        http.DefaultRequestHeaders.Accept.Add(new MediaTypeWithQualityHeaderValue("application/json"));
        http.DefaultRequestHeaders.Add("X-EzConnect-Version", "6.8.1");
        http.DefaultRequestHeaders.UserAgent.ParseAdd("RouteFinder/0.1");
    }

    public async Task<AuthTokens> LoginAsync(string email, string password, DeviceDescriptor device, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(device);
        if (string.IsNullOrWhiteSpace(email) || string.IsNullOrEmpty(password)) throw new ArgumentException("Email and password are required.");
        if (device.DeviceHash.Length != 64 || device.DeviceHash.Any(c => !char.IsAsciiHexDigit(c))) throw new ArgumentException("A real 64-character SHA-256 device hash is required; device identity is not generated by this adapter.");
        var payload = new Dictionary<string, object?>
        {
            ["email"] = email.Trim(), ["password"] = password,
            ["device"] = new Dictionary<string, object?>
            {
                ["device_hash"] = device.DeviceHash, ["os_name"] = device.OsName, ["os_version"] = device.OsVersion,
                ["hostname"] = device.Hostname, ["cpu_model"] = device.CpuModel ?? "", ["gpu_model"] = device.GpuModel ?? "",
                ["motherboard_model"] = device.MotherboardModel ?? "", ["system_uuid"] = device.SystemUuid ?? "",
                ["app_version"] = device.AppVersion, ["wiresock_version"] = device.WiresockVersion
            }
        };
        var response = await Send(HttpMethod.Post, LoginOrigin, "/api/desktop/auth/login", payload, null, ct);
        if (Bool(response, "mismatch")) throw new EzConnectServiceException("EZConnect rejected this device identity. Resolve the device registration in your account.", 200, "DEVICE_MISMATCH");
        return new(RequiredText(response, "access_token"), RequiredText(response, "refresh_token"), Number(response, "expires_in"), Number(response, "refresh_expires_in"));
    }

    public async Task<BootstrapData> BootstrapAsync(string accessToken, CancellationToken ct = default)
    {
        RequireToken(accessToken);
        var response = await Send(HttpMethod.Get, LoginOrigin, "/api/desktop/bootstrap", null, accessToken, ct);
        return ParseBootstrap(response);
    }

    public async Task<AuthTokens> RefreshAsync(string refreshToken, CancellationToken ct = default)
    {
        RequireToken(refreshToken);
        var response = await Send(HttpMethod.Post, LoginOrigin, "/api/desktop/auth/refresh",
            new Dictionary<string, string> { ["refresh_token"] = refreshToken }, null, ct);
        return new(RequiredText(response, "access_token"), First(Text(response, "refresh_token"), refreshToken),
            Number(response, "expires_in"), Number(response, "refresh_expires_in"));
    }

    public async Task SignOutAsync(string refreshToken, CancellationToken ct = default)
    {
        RequireToken(refreshToken);
        await Send(HttpMethod.Post, LoginOrigin, "/api/desktop/auth/logout",
            new Dictionary<string, string> { ["refresh_token"] = refreshToken }, null, ct, allowEmpty: true);
    }

    public static BootstrapData ParseBootstrap(JsonElement response)
    {
        Object(response);
        var routes = new List<ServiceRoute>();
        if (Field(response, "routes") is { ValueKind: JsonValueKind.Array } routeArray)
            foreach (var item in routeArray.EnumerateArray())
            {
                var name = Text(item, "name"); var region = Text(item, "region_code");
                if (name.Length > 0 && region.Length > 0) routes.Add(new(name, region, Text(item, "city_name"), Bool(item, "ipv6_enabled")));
            }
        var games = new List<CatalogGame>();
        if (Field(response, "games") is { ValueKind: JsonValueKind.Array } gameArray)
            foreach (var item in gameArray.EnumerateArray())
            {
                string name = Text(item, "name"); if (name.Length == 0) continue;
                var executables = Csv(Field(item, "executable_name")).Concat(Csv(Field(item, "exe_name"))).Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
                games.Add(new(name, executables, Csv(Field(item, "global_disallowed_ips")), item.Clone())
                {
                    CatalogId = ReadCatalogId(Field(item, "id")),
                    IsApplication = string.Equals(Text(item, "kind").Trim(), "app", StringComparison.OrdinalIgnoreCase),
                    RecommendedRegion = Text(item, "best_region").Trim(),
                    Servers = ReadGameServers(item),
                    LinkedAppNames = Csv(Field(item, "linked_app_names")),
                    IncompatibleAppNames = Csv(Field(item, "incompatible_app_names"))
                });
            }
        return new(routes, games, Text(response, "news"), response.Clone());
    }

    public async Task<ProvisionedSession> ConnectAsync(ServiceRoute route, string publicKey, string privateKey, string accessToken, CancellationToken ct = default)
    {
        RequireToken(accessToken); ArgumentNullException.ThrowIfNull(route);
        ValidateKey(publicKey); ValidateKey(privateKey);
        var secret = Convert.FromBase64String(privateKey);
        try { if (!Convert.FromBase64String(publicKey).SequenceEqual(WireGuardKeys.PublicFromPrivate(secret))) throw new ArgumentException("The supplied WireGuard public and private keys do not form a pair."); }
        finally { System.Security.Cryptography.CryptographicOperations.ZeroMemory(secret); }
        var payload = new Dictionary<string, string> { ["route_name"] = route.Name, ["region_code"] = route.RegionCode, ["client_public_key"] = publicKey };
        var response = await Send(HttpMethod.Post, PoolOrigin, "/api/desktop/sessions/connect", payload, accessToken, ct);
        try { return ParseProvisionedSession(response, route, privateKey); }
        catch (Exception error) when (error is FormatException or ArgumentException)
        {
            var sessionId = Text(response, "session_id");
            if (sessionId.Length > 0)
            {
                try { await DisconnectAsync(sessionId, accessToken, CancellationToken.None); }
                catch (Exception cleanupError) { throw new PendingSessionCleanupException(sessionId, cleanupError); }
            }
            var config = Field(response, "config");
            var cleanup = sessionId.Length > 0 ? "The temporary session was released." : "No usable session ID was returned. Release could not be confirmed.";
            throw new EzConnectServiceException(
                $"EZConnect returned an unusable WireGuard profile. {error.Message} " +
                $"Response types: session_id={Field(response, "session_id").ValueKind}, config={config.ValueKind}, " +
                $"Interface={Field(config, "Interface").ValueKind}, Peer={Field(config, "Peer").ValueKind}, " +
                $"routes={Field(response, "routes").ValueKind}, config.routes={Field(config, "routes").ValueKind}. " +
                $"Field types: {DescribeFields(response, "response")}; {DescribeFields(config, "config")}; " +
                $"{DescribeFields(Field(config, "Interface"), "Interface")}; {DescribeFields(Field(config, "Peer"), "Peer")}. {cleanup}",
                code: sessionId.Length > 0 ? "ROUTE_PROFILE_RELEASED" : null);
        }
    }

    public async Task DisconnectAsync(string sessionId, string accessToken, CancellationToken ct = default)
    {
        RequireToken(accessToken);
        if (string.IsNullOrWhiteSpace(sessionId)) throw new ArgumentException("A session ID is required.");
        await Send(HttpMethod.Post, PoolOrigin, "/api/desktop/sessions/disconnect", new Dictionary<string, string> { ["session_id"] = sessionId }, accessToken, ct, allowEmpty: true);
    }

    public static ProvisionedSession ParseProvisionedSession(JsonElement body, ServiceRoute route, string privateKey)
    {
        Object(body);
        string sessionId = RequiredText(body, "session_id");
        var (configuration, profile) = ParseConfiguration(body, route.Name, privateKey, route.OverIpv6);
        return new(sessionId, configuration, profile);
    }

    public static string ImportConfiguration(string json, string name, Func<string> readPrivateKey)
    {
        using var document = JsonDocument.Parse(json);
        var body = document.RootElement;
        Object(body);
        var config = Field(body, "config");
        if (config.ValueKind != JsonValueKind.Object)
            throw new FormatException("Import a complete EZConnect WireGuard configuration. A route list alone is missing tunnel settings.");
        var routeName = Text(body, "route_name");
        if (RouteEntries(body, config) is { ValueKind: JsonValueKind.Array } routes && routes.GetArrayLength() > 1)
        {
            if (routeName.Length == 0 || routes.EnumerateArray().Count(route =>
                Text(route, "name").Equals(routeName, StringComparison.OrdinalIgnoreCase)) != 1)
                throw new FormatException("This file contains multiple routes. Set route_name to the exact name of the route you want to import.");
        }
        var privateKey = Text(Field(config, "Interface"), "PrivateKey");
        if (privateKey.Length == 0) privateKey = readPrivateKey();
        return ParseConfiguration(body, routeName.Length == 0 ? name : routeName, privateKey).Configuration;
    }

    static (string Configuration, TunnelProfile Profile) ParseConfiguration(JsonElement body, string routeName, string privateKey, bool overIpv6 = false)
    {
        ValidateKey(privateKey);
        var config = Field(body, "config");
        if (config.ValueKind != JsonValueKind.Object) throw new FormatException("Service response has no usable config object. The service session may need cleanup.");
        var iface = Field(config, "Interface"); var peer = Field(config, "Peer");
        JsonElement entry = default;
        if (RouteEntries(body, config) is { ValueKind: JsonValueKind.Array } entries)
        {
            var candidates = entries.EnumerateArray().ToArray();
            entry = candidates.FirstOrDefault(x => Text(x, "name").Equals(routeName, StringComparison.OrdinalIgnoreCase));
            if (entry.ValueKind == JsonValueKind.Undefined && candidates.Length == 1) entry = candidates[0];
        }
        string address = First(CsvText(Field(iface, "Address")), CsvText(Field(config, "address")), CsvText(Field(body, "address")));
        string peerKey = First(Text(peer, "PublicKey"), Text(config, "peer_public_key"));
        string endpoint = overIpv6
            ? First(Text(entry, "route_ipv6_endpoint"), Text(config, "route_ipv6_endpoint"), Text(body, "route_ipv6_endpoint"))
            : First(Text(entry, "route_endpoint"), Text(config, "route_endpoint"), Text(body, "route_endpoint"), Text(peer, "Endpoint"));
        if (overIpv6 && endpoint.Length == 0)
            throw new FormatException("This session did not supply an IPv6 endpoint.");
        int? port = Number(peer, "Port") ?? Number(config, "peer_port");
        var missing = new List<string>();
        if (address.Length == 0) missing.Add("interface address");
        if (peerKey.Length == 0) missing.Add("peer public key");
        if (endpoint.Length == 0) missing.Add("route endpoint");
        if (missing.Count > 0) throw new FormatException("Missing " + string.Join(", ", missing) + ".");
        endpoint = WithPort(endpoint, port);
        if (overIpv6 && (!System.Net.IPAddress.TryParse(TunnelProfile.SplitEndpoint(endpoint).Host, out var ipv6) ||
            ipv6.AddressFamily != System.Net.Sockets.AddressFamily.InterNetworkV6))
            throw new FormatException("The service did not supply a numeric IPv6 endpoint.");
        var profile = new TunnelProfile { Name = routeName };
        profile.Interface["PrivateKey"] = privateKey;
        profile.Interface["Address"] = address;
        profile.Interface["MTU"] = (Number(iface, "MTU") ?? Number(config, "mtu") ?? 1380).ToString(System.Globalization.CultureInfo.InvariantCulture);
        string dns = First(CsvText(Field(entry, "route_dns")), CsvText(Field(config, "route_dns")), CsvText(Field(iface, "DNS")));
        if (dns.Length > 0) profile.Interface["DNS"] = dns;
        profile.Peer["PublicKey"] = peerKey; profile.Peer["Endpoint"] = endpoint;
        profile.Peer["AllowedIPs"] = First(CsvText(Field(entry, "route_allowedips")), CsvText(Field(config, "route_allowedips")), CsvText(Field(peer, "AllowedIPs")), "0.0.0.0/0");
        string psk = Text(peer, "PresharedKey"); if (psk.Length > 0) profile.Peer["PresharedKey"] = psk;
        var keepalive = Number(peer, "PersistentKeepalive"); if (keepalive != null) profile.Peer["PersistentKeepalive"] = keepalive.Value.ToString();
        string proxy = First(Text(entry, "proxy_ip"), Text(config, "proxy_ip"));
        if (proxy.Length > 0)
        {
            profile.Interface["Socks5Proxy"] = proxy;
            profile.Interface["Socks5ProxyUsername"] = First(Text(entry, "proxy_username"), Text(config, "proxy_username"));
            profile.Interface["Socks5ProxyPassword"] = First(Text(entry, "proxy_password"), Text(config, "proxy_password"));
        }
        if (Bool(entry, "amnezia_enabled") || Bool(config, "amnezia_enabled"))
        {
            string[][] fields = [["Jc", "junk_count", "3"], ["Jmin", "junk_minimum", "50"], ["Jmax", "junk_maximum", "1000"], ["Jd", "junk_delay", "0"], ["Id", "imitation_id", ""], ["Ip", "imitation_ip", ""], ["Ib", "imitation_ib", ""]];
            foreach (var map in fields)
            {
                var value = First(Scalar(Field(entry, map[1])), Scalar(Field(config, map[1])), map[2]);
                if (value.Length > 0) profile.Interface[map[0]] = value;
            }
        }
        profile.Validate();
        var text = new StringBuilder("[Interface]\r\n");
        foreach (var item in profile.Interface) text.Append(item.Key).Append(" = ").Append(item.Value).Append("\r\n");
        text.Append("\r\n[Peer]\r\n"); foreach (var item in profile.Peer) text.Append(item.Key).Append(" = ").Append(item.Value).Append("\r\n");
        return (text.ToString(), profile);
    }

    async Task<JsonElement> Send(HttpMethod method, Uri origin, string path, object? payload, string? accessToken, CancellationToken ct, bool allowEmpty = false)
    {
        using var deadline = CancellationTokenSource.CreateLinkedTokenSource(ct);
        deadline.CancelAfter(http.Timeout);
        ct = deadline.Token;
        using var request = new HttpRequestMessage(method, new Uri(origin, path));
        if (payload != null) request.Content = JsonContent.Create(payload);
        if (accessToken != null) request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", accessToken);
        using var response = await http.SendAsync(request, HttpCompletionOption.ResponseHeadersRead, ct);
        if (response.Content.Headers.ContentLength > MaxResponseBytes) throw new EzConnectServiceException("Service response exceeds the supported size.", (int)response.StatusCode);
        using var stream = await response.Content.ReadAsStreamAsync(ct); using var buffer = new MemoryStream(); var chunk = new byte[16384];
        while (true) { int read = await stream.ReadAsync(chunk, ct); if (read == 0) break; if (buffer.Length + read > MaxResponseBytes) throw new EzConnectServiceException("Service response exceeds the supported size."); await buffer.WriteAsync(chunk.AsMemory(0, read), ct); }
        if (!response.IsSuccessStatusCode)
        {
            string? code = null;
            try { using var error = JsonDocument.Parse(buffer.ToArray()); code = Text(error.RootElement, "error_code"); } catch (JsonException) { }
            if (code?.Length > 100 || code?.Any(c => !char.IsAsciiLetterOrDigit(c) && c != '_') == true) code = null;
            var retryAfter = response.Headers.RetryAfter?.Delta;
            if (response.Headers.RetryAfter?.Date is DateTimeOffset retryAt)
                retryAfter = retryAt - DateTimeOffset.UtcNow;
            throw new EzConnectServiceException($"EZConnect refused the request (HTTP {(int)response.StatusCode}" + (string.IsNullOrWhiteSpace(code) ? ")." : $", {code})."), (int)response.StatusCode, code, retryAfter);
        }
        if (allowEmpty && buffer.Length == 0) return default;
        try
        {
            using var document = JsonDocument.Parse(buffer.ToArray()); Object(document.RootElement);
            if (Field(document.RootElement, "success") is { ValueKind: JsonValueKind.False }) throw new EzConnectServiceException("EZConnect refused the request (success=false).", (int)response.StatusCode);
            return document.RootElement.Clone();
        }
        catch (JsonException) { throw new EzConnectServiceException("EZConnect returned an invalid JSON response.", (int)response.StatusCode); }
    }
    static void RequireToken(string token) { if (string.IsNullOrWhiteSpace(token) || token.Any(char.IsControl)) throw new ArgumentException("A valid access token is required."); }
    static JsonElement RouteEntries(JsonElement body, JsonElement config) =>
        new[] { Field(Field(config, "Peer"), "routes"), Field(body, "routes"), Field(config, "routes") }
            .FirstOrDefault(routes => routes.ValueKind == JsonValueKind.Array && routes.GetArrayLength() > 0);

    static string DescribeFields(JsonElement value, string label)
    {
        string[] names = ["address", "Address", "PublicKey", "Endpoint", "Port", "peer_public_key",
            "peer_port", "route_endpoint", "route_ipv6_endpoint", "routes", "server", "ip", "server_ip"];
        return label + " [" + string.Join(", ", names
            .Select(name => (Name: name, Kind: Field(value, name).ValueKind))
            .Where(field => field.Kind != JsonValueKind.Undefined)
            .Select(field => $"{field.Name}={field.Kind}")) + "]";
    }
    static void ValidateKey(string value) { try { if (Convert.FromBase64String(value).Length == 32) return; } catch (FormatException) { } throw new ArgumentException("A base64-encoded 32-byte WireGuard key is required."); }
    static void Object(JsonElement element) { if (element.ValueKind != JsonValueKind.Object) throw new FormatException("Expected a JSON object."); }
    static JsonElement Field(JsonElement item, string name) => item.ValueKind == JsonValueKind.Object && item.TryGetProperty(name, out var field) ? field : default;
    static string Text(JsonElement item, string name) => Field(item, name).ValueKind == JsonValueKind.String ? Field(item, name).GetString() ?? "" : "";
    static string RequiredText(JsonElement item, string name) => Text(item, name) is { Length: > 0 } result ? result : throw new FormatException($"Service response is missing {name}.");
    static bool Bool(JsonElement item, string name) => Field(item, name).ValueKind == JsonValueKind.True;
    static int? Number(JsonElement item, string name) => Field(item, name) is var v && ((v.ValueKind == JsonValueKind.Number && v.TryGetInt32(out int n)) || (v.ValueKind == JsonValueKind.String && int.TryParse(v.GetString(), out n))) ? n : null;
    static string Scalar(JsonElement value) => value.ValueKind is JsonValueKind.String ? value.GetString() ?? "" : value.ValueKind is JsonValueKind.Number ? value.GetRawText() : "";
    static long? ReadCatalogId(JsonElement value)
    {
        if (value.ValueKind == JsonValueKind.Number && value.TryGetInt64(out long number) && number > 0)
            return number;
        if (value.ValueKind == JsonValueKind.String &&
            long.TryParse(value.GetString(), System.Globalization.NumberStyles.None,
                System.Globalization.CultureInfo.InvariantCulture, out long parsed) && parsed > 0)
            return parsed;
        return null;
    }

    static GameServer[] ReadGameServers(JsonElement game)
    {
        var servers = new List<GameServer>();
        foreach (string key in new[] { "game_anchors", "anchors" })
        {
            if (Field(game, key) is not { ValueKind: JsonValueKind.Array } entries) continue;
            foreach (var entry in entries.EnumerateArray())
                if (System.Net.IPAddress.TryParse(Text(entry, "ip"), out var address) &&
                    address.AddressFamily == System.Net.Sockets.AddressFamily.InterNetwork)
                    servers.Add(new(Text(entry, "country_code"), Text(entry, "city"), address));
        }
        return servers.DistinctBy(server => server.Address).ToArray();
    }

    public static (string[] Ips, string[] Domains) GetGameBypass(CatalogGame game, string region)
    {
        var ips = new List<string>(game.GlobalDisallowedIps);
        var domains = new List<string>(Csv(Field(game.Raw, "global_disallowed_domains")));
        foreach (string key in new[] { "region_disallowed_config", "region_rules" })
        {
            var rules = Field(game.Raw, key);
            if (rules.ValueKind == JsonValueKind.Object)
            {
                foreach (var entry in rules.EnumerateObject())
                    if (entry.Name.Equals(region, StringComparison.OrdinalIgnoreCase))
                        AddRule(entry.Value);
            }
            else if (rules.ValueKind == JsonValueKind.Array)
            {
                foreach (var entry in rules.EnumerateArray())
                    if (Text(entry, "region_code").Equals(region, StringComparison.OrdinalIgnoreCase))
                        AddRule(entry);
            }
        }
        return (ips.Distinct(StringComparer.OrdinalIgnoreCase).ToArray(),
            domains.Distinct(StringComparer.OrdinalIgnoreCase).ToArray());

        void AddRule(JsonElement rule)
        {
            ips.AddRange(Csv(Field(rule, "disallowed_ips")));
            domains.AddRange(Csv(Field(rule, "disallowed_domains")));
        }
    }

    static string[] Csv(JsonElement item)
    {
        if (item.ValueKind == JsonValueKind.Array) return item.EnumerateArray().Where(x => x.ValueKind == JsonValueKind.String).SelectMany(Csv).ToArray();
        if (item.ValueKind != JsonValueKind.String) return [];
        string text = (item.GetString() ?? "").Trim();
        if (text.StartsWith('['))
        {
            try { using var list = JsonDocument.Parse(text); if (list.RootElement.ValueKind == JsonValueKind.Array) return Csv(list.RootElement); }
            catch (JsonException) { /* Preserve unsupported text so profile validation fails closed. */ }
        }
        return text.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
    }
    static string CsvText(JsonElement item) => string.Join(",", Csv(item));
    static string First(params string[] values) => values.FirstOrDefault(x => !string.IsNullOrWhiteSpace(x)) ?? "";
    static string WithPort(string endpoint, int? port)
    {
        try { TunnelProfile.SplitEndpoint(endpoint); return endpoint; } catch (FormatException) { }
        if (port is < 1 or > 65535 or null) throw new FormatException("Service route endpoint has no valid port.");
        string host = endpoint.Trim('[', ']'); return host.Contains(':') ? $"[{host}]:{port}" : $"{host}:{port}";
    }
    public void Dispose() => http.Dispose();
}
